class RecordingCleaner:
    """Stands in for the cleaner and records which path the handler chose."""

    def __init__(self) -> None:
        self.paths: list[str] = []

    async def clean(self, text: str) -> str:
        self.paths.append("document")
        return text

    async def clean_transcript(self, text: str, *, use_model: bool = True) -> str:
        self.paths.append("transcript")
        return text


class TestCleaning:
    """
    A document is not a transcript, and used to be cleaned as though it were.

    The transcript rules delete every parenthesised and bracketed span, so a
    maths or computer-science PDF lost the notation it is made of, silently,
    before the knowledge core and every artifact under it were built on it.
    """

    def test_a_document_keeps_mathematical_and_bracketed_notation(self):
        cleaned = asyncio.run(TextCleaner().clean(PDF_TEXT))

        for notation in ("f(x) = 2x", "[0,1]", "O(n log n)", "[Knuth 1998]", "NOTE:", "3:14"):
            assert notation in cleaned, f"cleaning ate {notation}"

    def test_page_markers_survive_a_document_clean(self):
        """The reader inserts them deliberately: they are structure, not noise."""
        cleaned = asyncio.run(TextCleaner().clean(PDF_TEXT))

        assert cleaned.startswith("--- Page 1 ---\n")
        assert "\n--- Page 2 ---\n" in cleaned

    def test_a_transcript_still_loses_asides_labels_and_timestamps(self):
        cleaned = asyncio.run(TextCleaner().clean_transcript(TRANSCRIPT_TEXT, use_model=False))

        for noise in ("(laughs)", "laughs", "[inaudible]", "inaudible", "SPEAKER:", "12:34"):
            assert noise not in cleaned, f"cleaning kept {noise}"
        assert "any two quorums intersect" in cleaned

    @pytest.mark.parametrize("source_type, path", [
        ("audio", "transcript"),
        ("video", "transcript"),
        ("youtube", "transcript"),
        ("pdf", "document"),
        ("pptx", "document"),
        ("md", "document"),
    ])
    def test_only_transcribed_sources_reach_the_transcript_rules(self, source_type, path):
        """Every source type used to get them, documents included."""
        cleaner = RecordingCleaner()

        asyncio.run(IngestHandler(cleaner=cleaner)._clean(PDF_TEXT, source_type))

        assert cleaner.paths == [path]


class TestTranscriptRepairKeepsTheSource:
    """
    The cleaning pass edits the transcript; it must never author a new one.

    This is the project's worst bug and its whole class. The offline provider
    hands a prompt its own input back only when it recognises the prompt as an
    edit, the cleaning prompt says "summarise", and the recogniser only knew
    "summarize", so a whole lecture was replaced by a synthetic study document.
    Nothing raised: the knowledge core and every artifact under it were built on
    text nobody had ever said.
    """

    def test_the_repair_prompt_is_recognised_as_an_edit_by_the_offline_provider(self):
        """
        The cheap half: the prompt and the recogniser pinned to each other.

        Neither can be reworded on its own after this, which is the failure that
        has no other symptom.
        """
        from backend.llm.offline import OfflineProvider
        from backend.pipeline.cleaning import REPAIR_PROMPT

        assert OfflineProvider._wants_the_source_back(REPAIR_PROMPT) is True

    def test_a_repaired_transcript_still_contains_the_lecture(self):
        """
        The whole class: the real cleaner, the real provider, a real transcript.

        Only the output can tell the difference between a repair and a
        replacement, so this reads the output rather than the recogniser.
        """
        from backend.llm.offline import OfflineProvider

        transcript = lecture_transcript()

        cleaned = asyncio.run(TextCleaner(OfflineProvider()).clean_transcript(transcript))

        assert LECTURE_SENTENCE in cleaned
        assert OFFLINE_MARKER not in cleaned
        assert cleaned.count(LECTURE_SENTENCE) >= transcript.count(LECTURE_SENTENCE) - 3
        assert len(cleaned) > len(transcript) * 0.9

    def test_the_ingest_handler_sends_a_transcript_down_that_same_path(self):
        """The door the bug came through: ingest picks the rules, then repairs."""
        from backend.llm.offline import OfflineProvider

        handler = IngestHandler(cleaner=TextCleaner(OfflineProvider()))

        cleaned = asyncio.run(handler._clean(lecture_transcript(), "audio"))

        assert LECTURE_SENTENCE in cleaned
        assert OFFLINE_MARKER not in cleaned


class TestGeneration:
    @pytest.mark.parametrize(
        "target",
        ["quiz", "flashcards", "notes", "slides", "study_guide", "cheatsheet", "mindmap", "exam"],
    )
    def test_every_artifact_type_generates_and_commits(self, database, project, knowledge_core, target):
        committed, job = run(database, project["id"], "generate", {
            "target_type": target, "source_artifact_ids": [knowledge_core["id"]],
        })
        assert committed, f"{target} did not commit"

        artifacts = database.select(
            "artifacts", [("project_id", f"eq.{project['id']}"), ("type", f"eq.{target}")]
        )
        assert len(artifacts) == 1
        assert artifacts[0]["content"]["data"]

        finished = database.get_job(job.id)
        assert finished["status"] == "completed"
        assert finished["result"]["artifact_type"] == target

    def test_an_exam_commits_its_rendered_booklet_alongside_the_questions(
        self, database, project, knowledge_core
    ):
        """
        The exam is the only type assembled from batches and typeset by a tool.

        A failed export is logged rather than raised, so the job completing says
        nothing about whether a booklet came out; the stored export is what has
        to be looked at. Which format arrives depends on whether pdflatex is
        installed, so both of its answers are accepted.
        """
        from backend.services.exports import MIME_TYPES
        from backend.services.files import get_file_store
        from backend.services.generators import EXAM_BATCHES

        committed, _ = run(database, project["id"], "generate", {
            "target_type": "exam", "source_artifact_ids": [knowledge_core["id"]],
        })
        assert committed

        exam = database.select(
            "artifacts", [("type", "eq.exam"), ("project_id", f"eq.{project['id']}")]
        )[0]

        questions = exam["content"]["data"]["questions"]
        assert len(questions) > max(count for _, count, _ in EXAM_BATCHES), "one batch is not an exam"
        assert [question["id"] for question in questions] == [
            f"Q-{number}" for number in range(1, len(questions) + 1)
        ], "batches are renumbered once they are merged"

        export = exam["content"]["binary"]
        assert export["format"] in {"pdf", "tex"}
        assert export["mime_type"] == MIME_TYPES[export["format"]]
        assert get_file_store().size_of(export["storage_path"]) == export["size_bytes"] > 0

