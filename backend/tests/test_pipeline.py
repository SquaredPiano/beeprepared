def exhausted_failure(monkeypatch, transport_error: Exception) -> BaseException:
    """Drive `_send` against a transport that always fails and return what it raised."""
    from backend.core.config import get_settings

    monkeypatch.setenv("OPENROUTER_API_KEY", "test-key")
    monkeypatch.setenv("LLM_MAX_RETRIES", "1")
    get_settings.cache_clear()

    async def always_fail(*args, **kwargs):
        raise transport_error

    monkeypatch.setattr(httpx.AsyncClient, "post", always_fail)

    with pytest.raises(LLMError) as raised:
        asyncio.run(OpenRouterProvider()._send({"model": "test"}))
    return raised.value


